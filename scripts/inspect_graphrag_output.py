"""Inspect the REAL Microsoft GraphRAG output (Milestone 9 done-criterion; prepares Milestone 10).
Run in the graphrag venv (needs pandas + pyarrow, which graphrag brings).

    python scripts\\inspect_graphrag_output.py

Prints and writes docs/data_dictionary/GRAPHRAG_OUTPUT_SCHEMA.md: every parquet file with its real
columns, types, null counts and a sample value - nothing assumed. It also tests whether every text unit
can be mapped back to OUR chunk ids through input_manifest.json (needed to keep provenance in Neo4j).
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys
from datetime import datetime, timezone

EXPECTED_BY_M10 = {   # informational only: what Milestone 10 will want to read; absence is reported, not assumed
    "entities": ["id", "title", "type", "description", "text_unit_ids"],
    "relationships": ["source", "target", "description", "weight", "text_unit_ids"],
    "communities": ["community", "level", "entity_ids", "relationship_ids"],
    "community_reports": ["community", "level", "title", "summary", "findings"],
    "text_units": ["id", "text", "document_id"],
    "documents": ["id", "title"],
}


def _short(value, limit=70) -> str:
    try:
        if hasattr(value, "tolist"):
            value = value.tolist()
        s = json.dumps(value, ensure_ascii=False, default=str) if not isinstance(value, str) else value
    except Exception:                                                    # noqa: BLE001
        s = str(value)
    s = s.replace("\n", " ")
    return s if len(s) <= limit else s[:limit - 3] + "..."


def describe_frame(df) -> list[dict]:
    rows = []
    for col in df.columns:
        series = df[col]
        sample = next((v for v in series if v is not None and not (isinstance(v, float) and v != v)), None)
        rows.append({"column": col, "dtype": str(series.dtype), "nulls": int(series.isna().sum()
                     if series.dtype != object else sum(1 for v in series if v is None)), "sample": _short(sample)})
    return rows


def map_text_units(manifest: dict, text_units, documents, input_dir: str) -> dict:
    """Locate every text unit inside its advisory file and list the chunk ids it overlaps."""
    title_to_key = {v["file"]: k for k, v in manifest.items()}
    doc_title = dict(zip(documents["id"], documents["title"])) if documents is not None else {}
    cache, mapped, unmapped, sample = {}, 0, 0, None
    for _, row in text_units.iterrows():
        fname = os.path.basename(str(doc_title.get(row.get("document_id"), "")))
        key = title_to_key.get(fname)
        if key is None:
            unmapped += 1
            continue
        if key not in cache:
            with open(os.path.join(input_dir, fname), encoding="utf-8") as fh:
                cache[key] = fh.read()
        text = str(row["text"]).strip()
        pos = cache[key].find(text) if text else -1
        if pos < 0:
            unmapped += 1
            continue
        end = pos + len(text)
        ids = [c["chunk_id"] for c in manifest[key]["chunks"] if c["start"] < end and c["end"] > pos]
        if ids:
            mapped += 1
            sample = sample or {"text_unit_id": row["id"], "chunk_ids": ids[:4]}
        else:
            unmapped += 1
    return {"mapped": mapped, "unmapped": unmapped, "sample": sample}


def main():
    import pandas as pd
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", default=os.path.join("data", "graphrag_outputs", "output"))
    ap.add_argument("--input-dir", default=os.path.join("data", "graphrag_outputs", "input"))
    ap.add_argument("--manifest", default=os.path.join("data", "graphrag_outputs", "input_manifest.json"))
    ap.add_argument("--doc", default=os.path.join("docs", "data_dictionary", "GRAPHRAG_OUTPUT_SCHEMA.md"))
    a = ap.parse_args()
    files = sorted(glob.glob(os.path.join(a.output, "*.parquet")))
    if not files:
        sys.exit(f"no .parquet files in {a.output} - has `graphrag index` finished?")
    frames, md = {}, [f"# GraphRAG output schema (as found, {datetime.now(timezone.utc):%Y-%m-%d})\n",
                      "Generated by `scripts/inspect_graphrag_output.py` from the real output - column names are not assumed.\n"]
    for f in files:
        name = os.path.splitext(os.path.basename(f))[0]
        df = pd.read_parquet(f)
        frames[name] = df
        desc = describe_frame(df)
        print(f"\n== {name}.parquet : {len(df)} rows, {len(df.columns)} columns")
        md.append(f"\n## {name}.parquet ({len(df)} rows)\n\n| column | dtype | nulls | sample |\n|---|---|---|---|")
        for d in desc:
            print(f"  {d['column']:<22} {d['dtype']:<12} nulls {d['nulls']:<5} e.g. {d['sample']}")
            md.append(f"| `{d['column']}` | {d['dtype']} | {d['nulls']} | {d['sample'].replace('|', '/')} |")
        want = EXPECTED_BY_M10.get(name)
        if want:
            missing = [c for c in want if c not in df.columns]
            line = f"Milestone 10 expects: {', '.join(want)} - " + ("all present." if not missing else f"MISSING: {', '.join(missing)}")
            print("  " + line)
            md.append("\n" + line)
    if os.path.isfile(a.manifest) and "text_units" in frames:
        with open(a.manifest, encoding="utf-8") as fh:
            manifest = json.load(fh)
        res = map_text_units(manifest, frames["text_units"], frames.get("documents"), a.input_dir)
        line = (f"Text units mapped back to our chunk ids: {res['mapped']} of {res['mapped'] + res['unmapped']}"
                + (f" (example: {json.dumps(res['sample'])})" if res["sample"] else ""))
        print("\n" + line)
        md.append("\n## Provenance\n\n" + line)
    os.makedirs(os.path.dirname(a.doc), exist_ok=True)
    with open(a.doc, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(md) + "\n")
    print("\nwrote", a.doc)


if __name__ == "__main__":
    main()
